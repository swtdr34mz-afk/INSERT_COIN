"""The intro's title, INSERT over COIN in Press Start 2P (SIL OFL 1.1, assets/fonts): a 90s arcade title, each of the type's
pixels drawn 4 x 4, a black outline 2 px round it and a dark drop shadow; rasterised at build time into 4 bits a pixel
(240 wide): 15 the face (app.c paints it in a gradient, row by row), 1 the outline, 2 the shadow, 0 nothing. And
"by swtdr34mz" small in the same type. Run by the build (fm1.toml gen): tools/gen_title.py --out GEN/title_data.h"""
import pathlib, sys
from PIL import Image, ImageDraw, ImageFont

out = pathlib.Path(sys.argv[sys.argv.index("--out") + 1])
root = pathlib.Path(__file__).resolve().parent.parent
font = ImageFont.truetype(str(root / "assets/fonts/PressStart2P-Regular.ttf"), 8)   # its own pixel grid: 8 px
SCALE, OUTLINE, SHADOW, GAP = 4, 2, 4, 8


def line(text, scale):
    im = Image.new("1", (8 * len(text) + 8, 12), 0)
    d = ImageDraw.Draw(im)
    d.fontmode = "1"
    d.text((0, 0), text, font=font, fill=1)
    im = im.crop(im.getbbox())
    return im.resize((im.size[0] * scale, im.size[1] * scale), Image.NEAREST)


a, b = line("INSERT", SCALE), line("COIN", SCALE + 1)
pad = OUTLINE + SHADOW
h = a.size[1] + GAP + b.size[1] + 2 * pad
face = Image.new("1", (240, h), 0)
face.paste(a, ((240 - a.size[0]) // 2, pad))
face.paste(b, ((240 - b.size[0]) // 2, pad + a.size[1] + GAP))
fp = face.load()


def lit(x, y):
    return 0 <= x < 240 and 0 <= y < h and fp[x, y]


nib = []
for y in range(h):
    for x in range(240):
        if lit(x, y):
            nib.append(15)
        elif any(lit(x + dx, y + dy) for dx in range(-OUTLINE, OUTLINE + 1) for dy in range(-OUTLINE, OUTLINE + 1)):
            nib.append(1)
        elif any(lit(x - SHADOW + dx, y - SHADOW + dy) for dx in range(-OUTLINE, OUTLINE + 1)
                 for dy in range(-OUTLINE, OUTLINE + 1)):
            nib.append(2)
        else:
            nib.append(0)
data = bytes(nib[i] | nib[i + 1] << 4 for i in range(0, len(nib), 2))
byl = Image.new("1", (8 * 13, 10), 0)   # "by swtdr34mz" small, in the same type, 1 x
dd = ImageDraw.Draw(byl)
dd.fontmode = "1"
dd.text((0, 0), "by swtdr34mz", font=font, fill=1)
byl = byl.crop(byl.getbbox())
bw, bh = byl.size
bp = byl.load()
by_bits = [1 if bp[x, y] else 0 for y in range(bh) for x in range(bw)]
rows = lambda bs: ",\n".join(",".join(str(v) for v in bs[i:i + 32]) for i in range(0, len(bs), 32))
split = pad + a.size[1] + GAP // 2      # the row between the two words (each word its own gradient)
text = ("/* generated by tools/gen_title.py: the intro's title (Press Start 2P, SIL OFL 1.1) */\n#pragma once\n"
        "#include <stdint.h>\n"
        f"#define TITLE_W 240\n#define TITLE_H {h}\n#define TITLE_SPLIT {split}\n"
        "static const uint8_t title_px[TITLE_W * TITLE_H / 2] = {\n" + rows(list(data)) + "\n};\n"
        f"#define BY_W {bw}\n#define BY_H {bh}\n"
        "static const uint8_t title_by[BY_W * BY_H] = {\n" + rows(by_bits) + "\n};\n")
out.parent.mkdir(parents=True, exist_ok=True)
if not out.exists() or out.read_text() != text:
    out.write_text(text)
print(f"title: {h} px high into {out}")
